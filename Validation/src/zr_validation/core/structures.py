#!/usr/bin/env python3

import math
from itertools import product
from pathlib import Path


def crystal(phase, a, c=None, repeat=(1, 1, 1), conventional=False):


    if phase == 'BCC':
        if conventional:
            cell = [(a,0.,0.), (0.,a,0.), (0.,0.,a)]
            basis = [(0.,0.,0.), (.5,.5,.5)]
        else:
            cell = [(-a/2,a/2,a/2), (a/2,-a/2,a/2), (a/2,a/2,-a/2)]
            basis = [(0.,0.,0.)]
    elif phase == 'FCC':
        if conventional:
            cell = [(a,0.,0.), (0.,a,0.), (0.,0.,a)]
            basis = [(0.,0.,0.), (0.,.5,.5), (.5,0.,.5), (.5,.5,0.)]
        else:
            cell = [(0.,a/2,a/2), (a/2,0.,a/2), (a/2,a/2,0.)]
            basis = [(0.,0.,0.)]
    elif phase == 'HCP':
        if c is None:
            raise ValueError('HCP requires c')
        cell = [(a,0.,0.), (-a/2, math.sqrt(3)*a/2,0.), (0.,0.,c)]
        basis = [(0.,0.,0.), (1/3,2/3,.5)]
    else:
        raise ValueError('Unknown phase: '+str(phase))
    nx,ny,nz=repeat
    assert min(repeat)>=1
    scaled_cell=[tuple(v*d for d in row) for row,v in zip(cell,repeat)]
    positions=[]
    for i,j,k in product(range(nx),range(ny),range(nz)):
        for bx,by,bz in basis:
            u=(i+bx,j+by,k+bz)
            positions.append(tuple(sum(u[m]*cell[m][axis] for m in range(3)) for axis in range(3)))
    return scaled_cell,positions


def dot(a,b): return sum(x*y for x,y in zip(a,b))
def norm(a): return math.sqrt(dot(a,a))


def prism(cell):

    a,b,c=cell
    lx=norm(a)
    ex=[x/lx for x in a]
    xy=dot(b,ex)
    ly=math.sqrt(max(0.,dot(b,b)-xy*xy))
    xz=dot(c,ex)
    yz=(dot(b,c)-xy*xz)/ly
    lz=math.sqrt(max(0.,dot(c,c)-xz*xz-yz*yz))
    assert min(lx,ly,lz)>0
    return lx,ly,lz,xy,xz,yz


def rotate_to_prism(cell,positions):
    a,b,c=cell
    lx,ly,lz,xy,xz,yz=prism(cell)

    ex=[x/lx for x in a]
    ey=[(b[i]-xy*ex[i])/ly for i in range(3)]
    ez=[(c[i]-xz*ex[i]-yz*ey[i])/lz for i in range(3)]
    return [(dot(r,ex),dot(r,ey),dot(r,ez)) for r in positions]


def write_lmp(path,cell,positions):
    path=Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    lx,ly,lz,xy,xz,yz=prism(cell)
    xyz=rotate_to_prism(cell,positions)
    has_tilt=any(abs(v)>1e-10 for v in (xy,xz,yz))
    with path.open('w') as f:
        f.write('Zr structure generated by structures_zr.py\n\n')
        f.write(f'{len(xyz)} atoms\n1 atom types\n\n')
        f.write(f'0.0 {lx:.16f} xlo xhi\n0.0 {ly:.16f} ylo yhi\n0.0 {lz:.16f} zlo zhi\n')
        if has_tilt: f.write(f'{xy:.16f} {xz:.16f} {yz:.16f} xy xz yz\n')
        f.write('\nAtoms # atomic\n\n')
        for atom_id,(x,y,z) in enumerate(xyz,1):
            f.write(f'{atom_id} 1 {x:.16f} {y:.16f} {z:.16f}\n')


def append_cfg(path,cell,positions,feature_text=''):
    with Path(path).open('a') as f:
        f.write('BEGIN_CFG\n Size\n')
        f.write(f'    {len(positions)}\n Supercell\n')
        for v in cell: f.write(f'    {v[0]:.16f} {v[1]:.16f} {v[2]:.16f}\n')
        f.write(' AtomData:  id type cartes_x cartes_y cartes_z\n')
        for i,(x,y,z) in enumerate(positions,1):
            f.write(f'    {i:6d} 0 {x:.16f} {y:.16f} {z:.16f}\n')
        if feature_text: f.write(f' Feature   {feature_text}\n')
        f.write('END_CFG\n\n')


def write_isolated_atom(path, size=20.0):
    s=float(size)
    cell=[(s,0.,0.),(0.,s,0.),(0.,0.,s)]
    write_lmp(path,cell,[(s/2,s/2,s/2)])
